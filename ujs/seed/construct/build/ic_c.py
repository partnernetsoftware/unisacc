"""Emit ujs/weights/ujs_ic_net.c — constructed ic stage as integer ask. [IC-1]"""
from __future__ import annotations

import os

from unisa.intnet import build
from ..gold import STAGES
from .. import catalog as C
from ..paths import weights_dir


def emit(path: str | None = None) -> str:
    net = build("ic", verify=True, stages=STAGES)
    S = STAGES["ic"]
    # fields: shape, op, guard
    shapes = list(C.SHAPES)
    ops = list(C.IC_OPS)
    guards = list(C.GUARDS)
    stubs = list(C.STUBS)
    assert [v for _, v in S.fields] == [tuple(shapes), tuple(ops), tuple(guards)]

    # Flatten IntNet: for each key index triple, we can also emit table
    # Prefer compact table (exact): 15*13*5 = 975 bytes
    table = []
    for si, sh in enumerate(shapes):
        for oi, op in enumerate(ops):
            for gi, gu in enumerate(guards):
                lab = net.predict((sh, op, gu))["y"]
                table.append(stubs.index(lab))

    lines = []
    lines.append("/* generated by ujs.construct.build.ic_c — do not edit */")
    lines.append("#include <stdint.h>")
    lines.append("typedef unsigned char u8;")
    lines.append("typedef unsigned int u32;")
    lines.append("#define IC_NSHAPE %d" % len(shapes))
    lines.append("#define IC_NOP %d" % len(ops))
    lines.append("#define IC_NGUARD %d" % len(guards))
    lines.append("static const u8 IC_TABLE[%d] = {" % len(table))
    for i in range(0, len(table), 16):
        chunk = table[i:i + 16]
        lines.append("  " + ",".join(str(x) for x in chunk) + ",")
    lines.append("};")
    lines.append(
        "u32 ujs_ic_ask(u32 shape, u32 op, u32 guard) {\n"
        "  if (shape >= IC_NSHAPE || op >= IC_NOP || guard >= IC_NGUARD)\n"
        "    return 0; /* interp */\n"
        "  return IC_TABLE[(shape * IC_NOP + op) * IC_NGUARD + guard];\n"
        "}\n"
    )
    # also export sizes for host
    lines.append("u32 ujs_ic_nshape(void) { return IC_NSHAPE; }")
    lines.append("u32 ujs_ic_nop(void) { return IC_NOP; }")
    lines.append("u32 ujs_ic_nguard(void) { return IC_NGUARD; }")

    text = "\n".join(lines) + "\n"
    if path is None:
        path = os.path.join(weights_dir(), "ujs_ic_net.c")
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    # verify table vs net
    for si, sh in enumerate(shapes):
        for oi, op in enumerate(ops):
            for gi, gu in enumerate(guards):
                got = stubs[table[(si * len(ops) + oi) * len(guards) + gi]]
                exp = net.predict((sh, op, gu))["y"]
                assert got == exp, (sh, op, gu, got, exp)
    return path


if __name__ == "__main__":
    print(emit())
