"""Emit browser ask tables + OP/TAG for in-page compile. [A-1][W]"""
from __future__ import annotations

import json
import os

from ..gold import STAGES, ALL
from .. import catalog as C
from ..bc import OP, TAG
from unisa.intnet import build


def emit(out_dir: str | None = None) -> str:
    from ..paths import practice_core, ujs_root
    ujs = ujs_root()
    # historically wrote web/compiler.gen.js; product lives in practice/core
    out_dir = out_dir or practice_core()
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "compiler.gen.js")

    tables = {}
    for name in ALL:
        st = STAGES[name]
        net = build(name, verify=True, stages=STAGES)
        # key: "v0|v1|..." -> class name
        field_vocabs = [list(v) for _, v in st.fields]
        classes = list(st.heads[0][1])
        flat = {}
        for key in st.keys():
            lab = net.predict(key)["y"]
            flat["|".join(str(x) for x in key)] = classes.index(lab)
        tables[name] = {
            "id": list(ALL).index(name),
            "fields": [{"name": n, "vocab": list(v)} for n, v in st.fields],
            "classes": classes,
            "map": flat,
        }

    lines = []
    lines.append("/* generated by ujs.construct.build.browser — do not edit */")
    lines.append("export const OP = %s;" % json.dumps(OP, sort_keys=True))
    lines.append("export const TAG = %s;" % json.dumps(TAG, sort_keys=True))
    lines.append("export const IC_OPS = %s;" % json.dumps(list(C.IC_OPS)))
    lines.append("export const STAGES = %s;" % json.dumps(tables, separators=(",", ":")))
    lines.append(
        "export function ask(stage, key) {\n"
        "  const st = STAGES[stage];\n"
        "  if (!st) throw new Error('unknown stage ' + stage);\n"
        "  const k = (Array.isArray(key) ? key : [key]).join('|');\n"
        "  const ix = st.map[k];\n"
        "  if (ix === undefined) throw new Error('ask ' + stage + ' ' + k);\n"
        "  return st.classes[ix];\n"
        "}\n"
    )
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


if __name__ == "__main__":
    print(emit())
