#!/usr/bin/env node
/**
 * Build asteroid.wasm = game core ONLY (no UJS VM).
 * Engine is separate: ship/gameEngine.wasm (= ujs_full.wasm).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { spawnSync } from "child_process";
import { compile } from "../../compiler.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, "../..");
const ujs = path.resolve(web, "..");
const native = path.join(ujs, "native");
const ship = here;

const simSrc = fs.readFileSync(path.join(web, "game/sim.ujs"), "utf8");
const { image, blob } = compile(simSrc);
const globals = blob.globals || [];

const embedH = path.join(native, "sim_embed.h");
const lines = [
  "/* auto-generated by build-asteroid.mjs — do not edit */",
  `#define SIM_IMAGE_LEN ${image.length}`,
  `#define SIM_N_GLOBALS ${globals.length}`,
  "static const unsigned char SIM_IMAGE[SIM_IMAGE_LEN] = {",
];
for (let i = 0; i < image.length; i += 16) {
  const chunk = [...image.slice(i, i + 16)].map((b) => "0x" + b.toString(16).padStart(2, "0"));
  lines.push("  " + chunk.join(", ") + (i + 16 < image.length ? "," : ""));
}
lines.push("};");
lines.push("static const char *SIM_GLOBALS[SIM_N_GLOBALS] = {");
for (const g of globals) lines.push(`  "${g}",`);
lines.push("};");
/* also emit JS-side meta for glue eng_sim_step */
fs.writeFileSync(embedH, lines.join("\n") + "\n");
fs.writeFileSync(path.join(ship, "sim.meta.json"), JSON.stringify({
  imageLen: image.length,
  globals,
  n: 480,
}));

const out = path.join(ship, "asteroid.wasm");
const cmd = [
  "zig", "cc", "-target", "wasm32-freestanding", "-O2",
  "-Wl,--no-entry",
  "-Wl,--export=game_init",
  "-Wl,--export=game_frame",
  "-Wl,--export=game_hud_ptr",
  "-Wl,--export=game_hud_size",
  "-Wl,--export=game_state_n",
  "-o", out,
  path.join(native, "uxe_asteroid.c"),
];
console.log(cmd.join(" "));
const r = spawnSync(cmd[0], cmd.slice(1), { stdio: "inherit" });
if (r.status !== 0) process.exit(r.status || 1);
console.log("asteroid.wasm", fs.statSync(out).size, "B (game only) · globals", globals.join(","));
