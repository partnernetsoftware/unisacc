STAGE_IDS = {n: i for i, n in enumerate(ALL)}

# Bytecode for the in-wasm VM (i64 stack machine).  Keep in sync with demo.js.
OP = {
    "nop": 0,
    "const_i64": 1,
    "load_l": 2,
    "store_l": 3,
    "drop": 4,
    "add": 5,
    "sub": 6,
    "mul": 7,
    "mod": 8,
    "lt": 9,
    "le": 10,
    "gt": 11,
    "ge": 12,
    "eq": 13,
    "ne": 14,
    "not": 15,
    "jump": 16,
    "jumpz": 17,
    "jumpnz": 18,
    "ret": 19,
}


def _escape_data(bs: bytes) -> str:
    return "".join("\\%02x" % b for b in bs)


def _pack_net(net) -> bytes:
    """Flat blob per stage:
      u32 H, u32 nfields, u32 ncls
      u32 offs[nfields]
      i32 b1[H]
      then for each input coord c in 0..h0-1:
        u16 nfeed; u16 units[nfeed]
      then for each unit j:
        u16 nent; (u16 cls, i16 w)[nent]
    h0 = offs[-1] + len(last vocab) — recovered from offs + field sizes via
    feeds length.
    """
    H = net.H
    nfields = len(net.offs)
    ncls = net.ncls["y"]
    h0 = len(net.feeds)
    out = bytearray()
    out += struct.pack("<III", H, nfields, ncls)
    out += struct.pack("<%dI" % nfields, *net.offs)
    # field widths so JS/wasm can map values → coords: store next off or h0
    widths = []
    for i in range(nfields):
        nxt = net.offs[i + 1] if i + 1 < nfields else h0
        widths.append(nxt - net.offs[i])
    out += struct.pack("<%dI" % nfields, *widths)
    out += struct.pack("<%di" % H, *net.b1)
    for feeds in net.feeds:
        out += struct.pack("<H", len(feeds))
        for u in feeds:
            out += struct.pack("<H", u)
    for j in range(H):
        ents = net.w2["y"][j]
        out += struct.pack("<H", len(ents))
        for cls, w in ents:
            out += struct.pack("<Hh", cls, w)
    return bytes(out)


def build_nets():
    return {n: build(n, verify=True, stages=STAGES) for n in ALL}


def emit_manifest(nets) -> dict:
    stages = {}
    for name in ALL:
        st = STAGES[name]
        net = nets[name]
        stages[name] = {
            "id": STAGE_IDS[name],
            "fields": [{"name": fn, "vocab": list(vo)} for fn, vo in st.fields],
            "classes": list(net.heads[0][1]),
            "units": net.nunits(),
            "rows": st.rows(),
        }
    return {"stages": stages, "ops": OP, "version": 1}


def emit_wat(nets) -> str:
    """One module: memory + ask + run."""
    blobs = []
    index = []  # (stage_id, offset, length)
    off = 0
    # leave [0, 65536) for VM scratch; put model data at 65536
    base = 65536
    off = base
    for name in ALL:
        raw = _pack_net(nets[name])
        index.append((STAGE_IDS[name], off, len(raw)))
        blobs.append((off, raw))
        off += len(raw)
        # align 8
        off = (off + 7) & ~7

    mem_pages = max(2, (off + 65535) // 65536)

    lines = []
    lines.append(";; generated by ujs.construct.build.web — do not edit")
    lines.append("(module")
    lines.append("  (memory (export \"memory\") %d)" % mem_pages)

    # data segments
    for o, raw in blobs:
        lines.append("  (data (i32.const %d) \"%s\")" % (o, _escape_data(raw)))

    # stage directory at fixed address 1024: 10 × {id,u32 off,u32 len} but we
    # use stage_id as index into a table at 1024.
    dir_base = 1024
    dir = bytearray()
    by_id = {sid: (o, ln) for sid, o, ln in index}
    for sid in range(len(ALL)):
        o, ln = by_id[sid]
        dir += struct.pack("<II", o, ln)
    lines.append("  (data (i32.const %d) \"%s\")" % (dir_base, _escape_data(bytes(dir))))

    # --- helpers to read LE ---
    lines.append("""
  (func $u16 (param $p i32) (result i32)
    (i32.load8_u (local.get $p))
    (i32.load8_u (i32.add (local.get $p) (i32.const 1)))
    (i32.shl (i32.const 8))
    i32.or)

  (func $i16 (param $p i32) (result i32)
    (call $u16 (local.get $p))
    (i32.extend16_s))

  (func $u32 (param $p i32) (result i32)
    (i32.load (local.get $p)))
""")

    # ask(stage_id, f0, f1, f2) -> class index
    # Uses at most 3 fields; unused should be 0.
    lines.append("""
  (func $ask (export "ask") (param $sid i32) (param $a i32) (param $b i32) (param $c i32) (result i32)
    (local $base i32) (local $p i32) (local $H i32) (local $nf i32) (local $nc i32)
    (local $h0 i32) (local $i i32) (local $j i32) (local $coord i32)
    (local $nfeed i32) (local $u i32) (local $best i32) (local $bv i32)
    (local $nent i32) (local $cls i32) (local $w i32) (local $hit i32)
    (local $zbase i32) (local $hitbase i32) (local $offsp i32) (local $widthp i32)
    (local $b1p i32) (local $feedp i32) (local $w2p i32) (local $tmp i32)

    ;; directory entry
    (local.set $base
      (call $u32 (i32.add (i32.const 1024) (i32.shl (local.get $sid) (i32.const 3)))))
    (local.set $p (local.get $base))
    (local.set $H (call $u32 (local.get $p)))
    (local.set $p (i32.add (local.get $p) (i32.const 4)))
    (local.set $nf (call $u32 (local.get $p)))
    (local.set $p (i32.add (local.get $p) (i32.const 4)))
    (local.set $nc (call $u32 (local.get $p)))
    (local.set $p (i32.add (local.get $p) (i32.const 4)))
    (local.set $offsp (local.get $p))
    (local.set $p (i32.add (local.get $p) (i32.shl (local.get $nf) (i32.const 2))))
    (local.set $widthp (local.get $p))
    (local.set $p (i32.add (local.get $p) (i32.shl (local.get $nf) (i32.const 2))))
    (local.set $b1p (local.get $p))
    (local.set $p (i32.add (local.get $p) (i32.shl (local.get $H) (i32.const 2))))
    (local.set $feedp (local.get $p))

    ;; h0 = sum widths
    (local.set $h0 (i32.const 0))
    (local.set $i (i32.const 0))
    (block $done_h0
      (loop $lh0
        (br_if $done_h0 (i32.ge_u (local.get $i) (local.get $nf)))
        (local.set $h0 (i32.add (local.get $h0)
          (call $u32 (i32.add (local.get $widthp) (i32.shl (local.get $i) (i32.const 2))))))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $lh0)))

    ;; clear hit[H] at mem 2048 and z[nc] at 2048+4*H
    (local.set $hitbase (i32.const 2048))
    (local.set $zbase (i32.add (local.get $hitbase) (i32.shl (local.get $H) (i32.const 2))))
    (local.set $i (i32.const 0))
    (block $cz
      (loop $lz
        (br_if $cz (i32.ge_u (local.get $i) (local.get $H)))
        (i32.store (i32.add (local.get $hitbase) (i32.shl (local.get $i) (i32.const 2))) (i32.const 0))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $lz)))
    (local.set $i (i32.const 0))
    (block $cz2
      (loop $lz2
        (br_if $cz2 (i32.ge_u (local.get $i) (local.get $nc)))
        (i32.store (i32.add (local.get $zbase) (i32.shl (local.get $i) (i32.const 2))) (i32.const 0))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $lz2)))

    ;; apply fields a,b,c
    (local.set $i (i32.const 0))
    (block $fields
      (loop $lf
        (br_if $fields (i32.ge_u (local.get $i) (local.get $nf)))
        (local.set $tmp (if (result i32) (i32.eq (local.get $i) (i32.const 0))
          (then (local.get $a))
          (else (if (result i32) (i32.eq (local.get $i) (i32.const 1))
            (then (local.get $b))
            (else (local.get $c))))))
        (local.set $coord (i32.add
          (call $u32 (i32.add (local.get $offsp) (i32.shl (local.get $i) (i32.const 2))))
          (local.get $tmp)))
        ;; walk feed list for coord: need pointer into feedp for coord-th list
        ;; scan from feedp
        (local.set $p (local.get $feedp))
        (local.set $j (i32.const 0))
        (block $find
          (loop $scan
            (br_if $find (i32.eq (local.get $j) (local.get $coord)))
            (local.set $nfeed (call $u16 (local.get $p)))
            (local.set $p (i32.add (local.get $p) (i32.const 2)))
            (local.set $p (i32.add (local.get $p) (i32.shl (local.get $nfeed) (i32.const 1))))
            (local.set $j (i32.add (local.get $j) (i32.const 1)))
            (br $scan)))
        (local.set $nfeed (call $u16 (local.get $p)))
        (local.set $p (i32.add (local.get $p) (i32.const 2)))
        (local.set $j (i32.const 0))
        (block $fe
          (loop $lfe
            (br_if $fe (i32.ge_u (local.get $j) (local.get $nfeed)))
            (local.set $u (call $u16 (local.get $p)))
            (local.set $p (i32.add (local.get $p) (i32.const 2)))
            (i32.store (i32.add (local.get $hitbase) (i32.shl (local.get $u) (i32.const 2)))
              (i32.add (i32.load (i32.add (local.get $hitbase) (i32.shl (local.get $u) (i32.const 2))))
                       (i32.const 1)))
            (local.set $j (i32.add (local.get $j) (i32.const 1)))
            (br $lfe)))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $lf)))

    ;; advance feedp to w2: skip all h0 feed lists
    (local.set $p (local.get $feedp))
    (local.set $j (i32.const 0))
    (block $sk
      (loop $lsk
        (br_if $sk (i32.ge_u (local.get $j) (local.get $h0)))
        (local.set $nfeed (call $u16 (local.get $p)))
        (local.set $p (i32.add (local.get $p) (i32.const 2)))
        (local.set $p (i32.add (local.get $p) (i32.shl (local.get $nfeed) (i32.const 1))))
        (local.set $j (i32.add (local.get $j) (i32.const 1)))
        (br $lsk)))
    (local.set $w2p (local.get $p))

    ;; accumulate logits
    (local.set $j (i32.const 0))
    (block $units
      (loop $lu
        (br_if $units (i32.ge_u (local.get $j) (local.get $H)))
        (local.set $hit (i32.load (i32.add (local.get $hitbase) (i32.shl (local.get $j) (i32.const 2)))))
        (local.set $hit (i32.add (local.get $hit)
          (i32.load (i32.add (local.get $b1p) (i32.shl (local.get $j) (i32.const 2))))))
        (local.set $nent (call $u16 (local.get $w2p)))
        (local.set $w2p (i32.add (local.get $w2p) (i32.const 2)))
        (if (i32.gt_s (local.get $hit) (i32.const 0))
          (then
            (local.set $i (i32.const 0))
            (block $ents
              (loop $le
                (br_if $ents (i32.ge_u (local.get $i) (local.get $nent)))
                (local.set $cls (call $u16 (local.get $w2p)))
                (local.set $w2p (i32.add (local.get $w2p) (i32.const 2)))
                (local.set $w (call $i16 (local.get $w2p)))
                (local.set $w2p (i32.add (local.get $w2p) (i32.const 2)))
                (i32.store (i32.add (local.get $zbase) (i32.shl (local.get $cls) (i32.const 2)))
                  (i32.add (i32.load (i32.add (local.get $zbase) (i32.shl (local.get $cls) (i32.const 2))))
                           (local.get $w)))
                (local.set $i (i32.add (local.get $i) (i32.const 1)))
                (br $le))))
          (else
            (local.set $w2p (i32.add (local.get $w2p) (i32.shl (local.get $nent) (i32.const 2))))))
        (local.set $j (i32.add (local.get $j) (i32.const 1)))
        (br $lu)))

    ;; argmax, ties -> smallest index
    (local.set $best (i32.const 0))
    (local.set $bv (i32.load (local.get $zbase)))
    (local.set $i (i32.const 1))
    (block $am
      (loop $lam
        (br_if $am (i32.ge_u (local.get $i) (local.get $nc)))
        (local.set $w (i32.load (i32.add (local.get $zbase) (i32.shl (local.get $i) (i32.const 2)))))
        (if (i32.gt_s (local.get $w) (local.get $bv))
          (then
            (local.set $bv (local.get $w))
            (local.set $best (local.get $i))))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $lam)))
    (local.get $best))
""")

    # jtape i64 VM — flat opcode dispatch (wat2wasm is picky about nested if)
    lines.append("""
  (func $run (export "run") (param $code i32) (param $len i32) (result i64)
    (local $pc i32) (local $end i32) (local $op i32) (local $sp i32)
    (local $a i64) (local $b i64) (local $slot i32) (local $tgt i32) (local $flag i32)
    (local.set $pc (local.get $code))
    (local.set $end (i32.add (local.get $code) (local.get $len)))
    (local.set $sp (i32.const 8192))
    (local.set $a (i64.const 0))
    (block $halt
      (loop $step
        (br_if $halt (i32.ge_u (local.get $pc) (local.get $end)))
        (local.set $op (i32.load8_u (local.get $pc)))
        (local.set $pc (i32.add (local.get $pc) (i32.const 1)))

        (block $next
          ;; 0 nop
          (br_if $next (i32.eqz (local.get $op)))

          ;; 1 const_i64
          (if (i32.eq (local.get $op) (i32.const 1))
            (then
              (i64.store (local.get $sp) (i64.load (local.get $pc)))
              (local.set $pc (i32.add (local.get $pc) (i32.const 8)))
              (local.set $sp (i32.add (local.get $sp) (i32.const 8)))
              (br $next)))

          ;; 2 load_l
          (if (i32.eq (local.get $op) (i32.const 2))
            (then
              (local.set $slot (i32.load8_u (local.get $pc)))
              (local.set $pc (i32.add (local.get $pc) (i32.const 1)))
              (i64.store (local.get $sp)
                (i64.load (i32.add (i32.const 4096) (i32.shl (local.get $slot) (i32.const 3)))))
              (local.set $sp (i32.add (local.get $sp) (i32.const 8)))
              (br $next)))

          ;; 3 store_l
          (if (i32.eq (local.get $op) (i32.const 3))
            (then
              (local.set $slot (i32.load8_u (local.get $pc)))
              (local.set $pc (i32.add (local.get $pc) (i32.const 1)))
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (i64.store (i32.add (i32.const 4096) (i32.shl (local.get $slot) (i32.const 3)))
                (i64.load (local.get $sp)))
              (br $next)))

          ;; 4 drop
          (if (i32.eq (local.get $op) (i32.const 4))
            (then
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (br $next)))

          ;; 5-8 binop
          (if (i32.and (i32.ge_u (local.get $op) (i32.const 5))
                       (i32.le_u (local.get $op) (i32.const 8)))
            (then
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $b (i64.load (local.get $sp)))
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $a (i64.load (local.get $sp)))
              (if (i32.eq (local.get $op) (i32.const 5))
                (then (local.set $a (i64.add (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 6))
                (then (local.set $a (i64.sub (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 7))
                (then (local.set $a (i64.mul (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 8))
                (then (local.set $a (i64.rem_s (local.get $a) (local.get $b)))))
              (i64.store (local.get $sp) (local.get $a))
              (local.set $sp (i32.add (local.get $sp) (i32.const 8)))
              (br $next)))

          ;; 9-14 cmp
          (if (i32.and (i32.ge_u (local.get $op) (i32.const 9))
                       (i32.le_u (local.get $op) (i32.const 14)))
            (then
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $b (i64.load (local.get $sp)))
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $a (i64.load (local.get $sp)))
              (local.set $flag (i32.const 0))
              (if (i32.eq (local.get $op) (i32.const 9))
                (then (local.set $flag (i64.lt_s (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 10))
                (then (local.set $flag (i64.le_s (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 11))
                (then (local.set $flag (i64.gt_s (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 12))
                (then (local.set $flag (i64.ge_s (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 13))
                (then (local.set $flag (i64.eq (local.get $a) (local.get $b)))))
              (if (i32.eq (local.get $op) (i32.const 14))
                (then (local.set $flag (i64.ne (local.get $a) (local.get $b)))))
              (i64.store (local.get $sp) (i64.extend_i32_u (local.get $flag)))
              (local.set $sp (i32.add (local.get $sp) (i32.const 8)))
              (br $next)))

          ;; 15 not
          (if (i32.eq (local.get $op) (i32.const 15))
            (then
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $a (i64.load (local.get $sp)))
              (i64.store (local.get $sp) (i64.extend_i32_u (i64.eqz (local.get $a))))
              (local.set $sp (i32.add (local.get $sp) (i32.const 8)))
              (br $next)))

          ;; 16 jump
          (if (i32.eq (local.get $op) (i32.const 16))
            (then
              (local.set $tgt (i32.load16_u (local.get $pc)))
              (local.set $pc (i32.add (local.get $code) (local.get $tgt)))
              (br $next)))

          ;; 17 jumpz
          (if (i32.eq (local.get $op) (i32.const 17))
            (then
              (local.set $tgt (i32.load16_u (local.get $pc)))
              (local.set $pc (i32.add (local.get $pc) (i32.const 2)))
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $a (i64.load (local.get $sp)))
              (if (i64.eqz (local.get $a))
                (then (local.set $pc (i32.add (local.get $code) (local.get $tgt)))))
              (br $next)))

          ;; 18 jumpnz
          (if (i32.eq (local.get $op) (i32.const 18))
            (then
              (local.set $tgt (i32.load16_u (local.get $pc)))
              (local.set $pc (i32.add (local.get $pc) (i32.const 2)))
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $a (i64.load (local.get $sp)))
              (if (i32.eqz (i64.eqz (local.get $a)))
                (then (local.set $pc (i32.add (local.get $code) (local.get $tgt)))))
              (br $next)))

          ;; 19 ret
          (if (i32.eq (local.get $op) (i32.const 19))
            (then
              (local.set $sp (i32.sub (local.get $sp) (i32.const 8)))
              (local.set $a (i64.load (local.get $sp)))
              (br $halt)))

          unreachable
        )
        (br $step)
      )
    )
    (local.get $a))
""")

    lines.append(")")
    return "\n".join(lines)


def encode_i64_program(ops_with_args) -> bytes:
    """ops_with_args: list of (name, *args) using OP names."""
    out = bytearray()
    for item in ops_with_args:
        name, *args = item if isinstance(item, tuple) else (item,)
        out.append(OP[name])
        if name == "const_i64":
            out += struct.pack("<q", int(args[0]))
        elif name in ("load_l", "store_l"):
            out.append(int(args[0]) & 0xFF)
        elif name in ("jump", "jumpz", "jumpnz"):
            out += struct.pack("<H", int(args[0]) & 0xFFFF)
    return bytes(out)


