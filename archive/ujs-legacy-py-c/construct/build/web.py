def _git_short() -> str:
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
        return out or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def write_build_json(out_dir: str) -> str:
    """Write ujs/core/BUILD.json — provenance fingerprint for prebuilt wasm."""
    from datetime import datetime, timezone

    artifacts = {}
    for name in BUILD_ARTIFACTS:
        path = os.path.join(out_dir, name)
        if not os.path.isfile(path):
            continue
        artifacts[name] = {
            "sha256": _sha256_file(path),
            "bytes": os.path.getsize(path),
        }
    rec = {
        "product": "ujs",
        "version": _pkg_version(),
        "git": _git_short(),
        "created": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "artifacts": artifacts,
        "suite": "tests/ujs.sh",
        "abi": list(BUILD_ABI),
    }
    path = os.path.join(out_dir, "BUILD.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(rec, f, indent=2, sort_keys=True)
        f.write("\n")
    return path


def web_build(out_dir: str) -> dict:
    os.makedirs(out_dir, exist_ok=True)
    nets = build_nets()
    wat = emit_wat(nets)
    wat_path = os.path.join(out_dir, "ujs_rt.wat")
    wasm_path = os.path.join(out_dir, "ujs_rt.wasm")
    with open(wat_path, "w") as f:
        f.write(wat)
    subprocess.check_call(["wat2wasm", wat_path, "-o", wasm_path])
    man = emit_manifest(nets)
    with open(os.path.join(out_dir, "manifest.json"), "w") as f:
        json.dump(man, f, indent=2, sort_keys=True)

    # demo bytecodes
    demos = {}
    demos["arith"] = {
        "title": "1 + 2 * 3",
        "src": "return 1 + 2 * 3;",
        "code": list(encode_i64_program([
            ("const_i64", 1), ("const_i64", 2), ("const_i64", 3),
            "mul", "add", "ret",
        ])),
        "expect": 7,
    }

    def size_of(ops):
        return len(encode_i64_program(ops))

    init = [("const_i64", 5), ("store_l", 0), ("const_i64", 1), ("store_l", 1)]
    # while (n > 0): gt then jumpz end
    head_ops = [("load_l", 0), ("const_i64", 0), "gt"]
    body_ops = [
        ("load_l", 1), ("load_l", 0), "mul", ("store_l", 1),
        ("load_l", 0), ("const_i64", 1), "sub", ("store_l", 0),
    ]
    init_sz = size_of(init)
    head_sz = size_of(head_ops)
    jz_sz = 3
    body_sz = size_of(body_ops)
    jmp_sz = 3
    loop_pc = init_sz
    end_pc = init_sz + head_sz + jz_sz + body_sz + jmp_sz
    prog = (init + head_ops + [("jumpz", end_pc)] + body_ops
            + [("jump", loop_pc)] + [("load_l", 1), "ret"])
    demos["fact"] = {
        "title": "fact(5)",
        "src": "let n=5; let f=1; while(n>0){f=f*n; n=n-1;} return f;",
        "code": list(encode_i64_program(prog)),
        "expect": 120,
    }

    with open(os.path.join(out_dir, "demos.json"), "w") as f:
        json.dump(demos, f, indent=2, sort_keys=True)

    magic = open(wasm_path, "rb").read(4)
    assert magic == b"\0asm", magic
    return {
        "wasm": wasm_path,
        "wat": wat_path,
        "bytes": os.path.getsize(wasm_path),
        "stages": len(ALL),
    }
