#!/usr/bin/env python3
"""Regenerate inventory in a private input snapshot and compare exact bytes."""
import difflib
import pathlib
import shutil
import subprocess
import sys
import tempfile
ROOT = pathlib.Path(__file__).resolve().parents[1]
def check(root):
    expected = (root / 'tests/INVENTORY.md').read_bytes()
    with tempfile.TemporaryDirectory(prefix='inventory-derived-') as d:
        tree = pathlib.Path(d)
        for relative in ('tests', 'exec', '.github/workflows'):
            source = root / relative
            if source.is_dir():
                shutil.copytree(source, tree / relative, ignore=shutil.ignore_patterns('__pycache__', 'build'))
        result = subprocess.run([sys.executable, str(tree / 'tests/inventory.py'), '--write', '--check'],
                                cwd=tree, capture_output=True, timeout=50)
        if result.returncode:
            sys.stdout.buffer.write(result.stdout)
            sys.stderr.buffer.write(result.stderr)
            return 1
        actual = (tree / 'tests/INVENTORY.md').read_bytes()
    if actual != expected:
        print('STALE tests/INVENTORY.md: regenerate with inventory.py --write')
        diff = difflib.unified_diff(expected.decode().splitlines(), actual.decode().splitlines(),
                                   fromfile='committed INVENTORY.md', tofile='regenerated INVENTORY.md', lineterm='')
        for line in diff: print(line)
        return 1
    print('inventory-derived: regenerated bytes match tests/INVENTORY.md')
    return 0
if __name__ == '__main__':
    try:
        raise SystemExit(check(pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) == 2 else ROOT))
    except (OSError, subprocess.TimeoutExpired) as e:
        print('inventory-derived: mechanism/timeout:', e, file=sys.stderr)
        raise SystemExit(2)
